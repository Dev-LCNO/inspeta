-- Inspeta — banco do backend real (Supabase / Postgres 15+).
--
-- Modelo: as regras ficam na API (função "api"), que é a única porta de entrada.
-- Cada entidade (formulário, inspeção, plano, membro...) é uma linha em "registros",
-- com a organização, a coleção, o id e o conteúdo em jsonb. Os índices abaixo cobrem
-- as buscas que a API faz fora do estado carregado (login por e-mail, link público do plano).
--
-- Acesso direto pelo cliente (anon/authenticated via PostgREST) é NEGADO: RLS ligado sem
-- nenhuma política. Só a API, com a chave de serviço, lê e grava.

create extension if not exists pgcrypto;

create table if not exists orgs (
  id uuid primary key default gen_random_uuid(),
  nome text not null check (length(trim(nome)) > 0),
  fuso_horario text not null default 'America/Sao_Paulo',
  contadores jsonb not null default '{}'::jsonb,   -- ex.: {"eventoSeq": 42}
  criado_em timestamptz not null default now()
);

create table if not exists registros (
  org_id uuid not null references orgs(id) on delete cascade,
  colecao text not null check (colecao in (
    'formularios','versoes','avaliados','inspecoes','eventos','planosModelo','planos','emails',
    'membros','funcoes','equipes','agendamentos','ocorrencias','aprovacoes','camposAvaliado')),
  id text not null,
  dados jsonb not null,
  atualizado timestamptz not null default now(),
  seq bigint generated by default as identity,   -- ordem de inserção (o histórico da inspeção depende dela)
  primary key (org_id, colecao, id)
);
create index if not exists registros_colecao on registros (org_id, colecao);
-- login: e-mail do membro -> organização
create index if not exists registros_membro_email on registros (lower(dados->>'email')) where colecao = 'membros';
-- link público do plano de ação (só o hash do token é guardado)
create index if not exists registros_plano_token on registros ((dados->>'token_hash')) where colecao = 'planos';
-- fila de e-mails ainda não enviados
create index if not exists registros_email_pendente on registros (org_id) where colecao = 'emails' and dados->>'status' = 'pendente';
-- versão publicada é imutável: impede UPDATE no conteúdo
create or replace function registros_versao_imutavel() returns trigger language plpgsql set search_path = '' as $$
begin
  if old.colecao = 'versoes' and old.dados is distinct from new.dados then
    raise exception 'versão publicada não pode ser alterada';
  end if;
  return new;
end $$;
drop trigger if exists registros_versao_imutavel on registros;
create trigger registros_versao_imutavel before update on registros for each row execute function registros_versao_imutavel();
-- client_uuid único por organização (reenvio do aparelho nunca duplica, nem em corrida)
create unique index if not exists registros_inspecao_client on registros (org_id, (dados->>'client_uuid')) where colecao = 'inspecoes';

-- anexos (fotos/assinaturas/logos). Em produção podem ir para o Storage (ANEXOS=storage);
-- esta tabela é o padrão e o que os testes locais usam.
create table if not exists anexos (
  org_id uuid not null references orgs(id) on delete cascade,
  id text not null,
  data_url text not null,
  bytes int not null,
  criado_em timestamptz not null default now(),
  primary key (org_id, id)
);

-- trilha de chamadas que alteram dados (quem, o quê, quando) — sem conteúdo pessoal
create table if not exists auditoria (
  id bigint generated always as identity primary key,
  org_id uuid references orgs(id) on delete cascade,
  membro_id text,
  metodo text not null,
  em timestamptz not null default now()
);
create index if not exists auditoria_org on auditoria (org_id, em desc);

alter table orgs enable row level security;
alter table registros enable row level security;
alter table anexos enable row level security;
alter table auditoria enable row level security;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on orgs, registros, anexos, auditoria from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on orgs, registros, anexos, auditoria from authenticated';
  end if;
end $$;
